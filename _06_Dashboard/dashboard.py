def _has_current_missing_weight_rca(data: dict[str, pd.DataFrame], ct_id: str) -> bool:
    """Return whether the current RCA data contains the missing-weight dose outcome."""
    rca = data["rca"]
    if rca.empty:
        return False
    rows = rca[
        rca["ct_id"].astype(str).eq(str(ct_id))
        & rca["rca_schema"].fillna("").astype(str).eq("dose_schema_v1")
    ]
    return rows["rca_label"].fillna("").astype(str).str.lower().eq("missing weight").any()


def _latest_recommendation(data: dict[str, pd.DataFrame], ct_id: str) -> tuple[pd.Series | None, bool]:
    """Return the latest persisted exam-level LLM recommendation and stale-state flag."""
    recommendations = data["recommendations"]
    if recommendations.empty:
        return None, False
    rows = recommendations[
        recommendations["ct_id"].astype(str).eq(str(ct_id))
        & recommendations["scope"].fillna("").astype(str).eq("exam")
    ].sort_values("created_at")
    if rows.empty:
        return None, False
    latest = rows.iloc[-1]
    input_json = _as_text(latest.get("input_json"))
    input_text = input_json.lower()
    has_missing_weight_input = "missing weight" in input_text or "patient weight missing" in input_text
    stale_missing_weight = _has_current_missing_weight_rca(data, ct_id) and not has_missing_weight_input
    return latest, stale_missing_weight


def _render_recommendation(data: dict[str, pd.DataFrame], ct_id: str) -> None:
    """Show the stored LLM report; never invoke an LLM from the dashboard."""
    recommendation, stale = _latest_recommendation(data, ct_id)
    st.subheader("Clinical summary")
    if recommendation is None:
        st.info(
            "The LLM report is not available for this patient yet. "
            "Generate it in the background with: python _04_Recommendations/generate_recommendations.py"
        )
        return
    if stale:
        st.warning(
            "The stored LLM report was generated before the current missing-weight dose logic. "
            "Regenerate recommendations in the background before using this narrative summary."
        )
        return

    source = _as_text(recommendation.get("source"), "stored")
    created_at = _as_text(recommendation.get("created_at"), "date unavailable")
    st.caption(f"Source: {source} | Generated: {created_at}")
    st.markdown(f"<div class='aq-llm'>{_as_text(recommendation.get('recommendation'))}</div>", unsafe_allow_html=True)


