def _selected_series_context(
    data: dict[str, pd.DataFrame],
    patient_series: pd.DataFrame,
    ct_id: str,
) -> tuple[pd.Series | None, pd.DataFrame, pd.DataFrame, list[Path]]:
    """Let the user pick one series and return its QC, RCA, and image context."""
    if patient_series.empty:
        return None, pd.DataFrame(), pd.DataFrame(), []

    st.markdown("<div class='aq-section-label'>Image and series selector</div>", unsafe_allow_html=True)
    ordered = patient_series.sort_values(["worst_status", "phase_name", "series_folder"], key=lambda column: column.map(lambda value: STATUS_ORDER.get(value, 99) if column.name == "worst_status" else str(value)))
    labels = [f"{row.phase_name or '-'} | {STATUS_LABELS.get(row.worst_status, row.worst_status)} | {row.series_folder}" for row in ordered.itertuples(index=False)]
    selected_label = st.selectbox("Series to review", labels, label_visibility="collapsed")
    selected = ordered.iloc[labels.index(selected_label)]
    series_folder = str(selected["series_folder"])

    quality_rows = data["image_quality"][
        data["image_quality"]["ct_id"].astype(str).eq(str(ct_id))
        & data["image_quality"]["series_folder"].astype(str).eq(series_folder)
    ].copy()
    rca_rows = data["rca"][
        data["rca"]["ct_id"].astype(str).eq(str(ct_id))
        & data["rca"]["series_folder"].astype(str).eq(series_folder)
    ].copy()
    image_paths = _image_paths_from_quality_rows(quality_rows)
    return selected, quality_rows, rca_rows, image_paths


