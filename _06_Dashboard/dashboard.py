def _render_roi_cards(quality_rows: pd.DataFrame) -> None:
    """Render ROI-level QC findings as compact cards for rapid clinical scanning."""
    if quality_rows.empty:
        st.info("No QC detail is available for this series.")
        return

    for _, row in quality_rows.sort_values(["status", "roi_name"], key=lambda column: column.map(lambda value: STATUS_ORDER.get(value, 99) if column.name == "status" else str(value))).iterrows():
        status = _as_text(row.get("status"), "missing")
        color = STATUS_COLORS.get(status, "#667085")
        value_label = _format_quality_number(_quality_field(row, "evaluated_value"))
        mean_label = f"{_format_quality_number(_quality_field(row, 'mean_hu'))} +/- {_format_quality_number(_quality_field(row, 'std_hu'))}"
        median_label = f"{_format_quality_number(_quality_field(row, 'median_hu'))} +/- {_format_quality_number(_quality_field(row, 'median_std_hu'))}"
        threshold_label = ""
        threshold_min_opt = _quality_field(row, "threshold_min_opt")
        if _as_text(threshold_min_opt):
            threshold_label = (
                f"<div><strong>Optimal:</strong> {_format_quality_number(threshold_min_opt)} to "
                f"{_format_quality_number(_quality_field(row, 'threshold_max_opt'))}</div>"
                f"<div><strong>Tolerance:</strong> {_format_quality_number(_quality_field(row, 'threshold_min_with_threshold'))} to "
                f"{_format_quality_number(_quality_field(row, 'threshold_max_with_threshold'))}</div>"
            )
        warning = _as_text(_quality_field(row, "warning"))
        warning_html = f"<div class='aq-roi-warning'><strong>Warning:</strong> {warning}</div>" if warning else ""
        attenuation_message = _as_text(_quality_field(row, "attenuation_message"))
        attenuation_html = ""
        if attenuation_message:
            consistency = _as_text(_quality_field(row, "attenuation_consistency"))
            consistency_color = "#b91c1c" if consistency == "incoherent" else "#0369a1"
            edge_count = _quality_field(row, "edge_slice_count")
            slice_label = f"first/last {int(float(edge_count))} vessel slices" if _as_text(edge_count) else "vessel endpoints"
            attenuation_html = (
                f"<div class='aq-attenuation' style='border-left-color:{consistency_color};'>"
                f"<strong>Attenuation consistency ({slice_label}):</strong><br>{attenuation_message}</div>"
            )
        st.markdown(
            f"""
            <div class="aq-card" style="border-left:5px solid {color};">
                <div class="aq-card-title">{_as_text(row.get('roi_name'), 'ROI')} - {STATUS_LABELS.get(status, status)}</div>
                <div class="aq-muted">{_as_text(row.get('metric_name'), 'metric')} | value: <strong>{value_label}</strong></div>
                <div><strong>Mean HU:</strong> {mean_label}</div>
                <div><strong>Median HU:</strong> {median_label}</div>
                {threshold_label}
                {attenuation_html}
                {warning_html}
            </div>
            """,
            unsafe_allow_html=True,
        )


