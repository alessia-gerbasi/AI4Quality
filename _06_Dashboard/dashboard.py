def _as_text(value: object, default: str = "") -> str:
    """Return a clean display string for values that may be NaN or None."""
    if value is None or pd.isna(value):
        return default
    text = str(value).strip()
    if text.lower() in {"", "nan", "none", "null"}:
        return default
    return text


def _sort_key(value: object) -> tuple[int, object]:
    """Sort numeric CT identifiers numerically and all other IDs alphabetically."""
    text = _as_text(value)
    return (0, int(text)) if text.isdigit() else (1, text)


def _read_json(value: object) -> dict:
    """Decode JSON stored in SQLite cells, returning an empty dict on bad input."""
    text = _as_text(value)
    if not text:
        return {}
    try:
        decoded = json.loads(text)
    except json.JSONDecodeError:
        return {}
    return decoded if isinstance(decoded, dict) else {}


def _quality_field(row: pd.Series, key: str, default: object = "") -> object:
    """Read a quality field from the normalized row or its persisted QC payload."""
    value = row.get(key)
    if value is not None and not (isinstance(value, float) and pd.isna(value)) and _as_text(value):
        return value
    return _read_json(row.get("qc_data_json")).get(key, default)


def _format_quality_number(value: object) -> str:
    if value is None or (isinstance(value, float) and pd.isna(value)) or _as_text(value) == "":
        return "n/a"
    try:
        return f"{float(value):.1f}"
    except (TypeError, ValueError):
        return _as_text(value, "n/a")


def _format_percentage(value: object) -> str:
    """Format a phase-prediction probability as a percentage."""
    if value is None or pd.isna(value):
        return "n/a"
    return f"{float(value) * 100.0:.1f}%"


def _phase_match_label(value: object) -> str:
    """Convert nullable dataframe booleans into a display label."""
    if value is None or (not isinstance(value, str) and pd.isna(value)):
        return "No prediction"
    return "Match" if bool(value) else "Mismatch"


def _normalize_phase_name(value: object) -> str:
    """Normalize phase labels before comparing stored and predicted phases."""
    return _as_text(value).lower().replace(" ", "_")


def _phase_prediction_matches(actual: str, predicted: str) -> bool:
    """Compare Italian stored phase labels with the model's English labels."""
    if not actual or not predicted:
        return False
    if actual == predicted:
        return True
    return (actual == "venosa" and "venous" in predicted) or (actual == "arteriosa" and "arterial" in predicted)


def _effective_phase(row: pd.Series) -> str:
    """Resolve the true phase using the same rule as quality-check evaluation."""
    phase = _normalize_phase_name(row.get("phase_name"))
    metadata = _read_json(row.get("series_data_json"))
    ct_type = _normalize_phase_name(metadata.get("CT_type"))
    if not phase and ct_type == "vascular":
        return "arteriosa"
    return phase


def _phase_prediction_map(data: dict[str, pd.DataFrame]) -> dict[tuple[str, str], dict[str, object]]:
    """Load phase predictions from QC artifact metadata for each series."""
    predictions: dict[tuple[str, str], dict[str, object]] = {}
    for _, row in data["image_quality"].iterrows():
        key = (str(row.get("ct_id")), _as_text(row.get("series_folder")))
        series_dir = _read_json(row.get("qc_data_json")).get("series_dir")
        phase_path = _resolve_artifact_path(series_dir)
        if phase_path is None:
            data_root = ROOT.parent / "DATA"
            ct_prefix = f"CT_QUALITY_{key[0]}_"
            series_name = key[1].lower()
            search_roots = [data_root / "CDI_NEXO_072026" / "2_nii", data_root]
            candidates = []
            for search_root in search_roots:
                candidates.extend(
                    path for path in search_root.glob(f"{ct_prefix}*/**/phase.json")
                    if series_name in path.parent.name.lower()
                )
                if candidates:
                    break
            if candidates:
                phase_path = candidates[0].parent
        if phase_path is None:
            continue
        phase_file = phase_path / "phase.json"
        if not phase_file.exists():
            continue
        try:
            with phase_file.open("r", encoding="utf-8") as stream:
                prediction = json.load(stream)
        except (OSError, json.JSONDecodeError):
            continue
        if isinstance(prediction, dict) and prediction.get("phase"):
            predictions[key] = prediction
    return predictions


def _join_unique(values: Iterable[object], fallback: str = "-") -> str:
    """Compact a column into a comma-separated list without repeated labels."""
    clean_values = sorted({_as_text(value) for value in values if _as_text(value)})
    return ", ".join(clean_values) if clean_values else fallback


def _worst_status(values: Iterable[object]) -> str:
    """Return the clinically most relevant QC status in a group of ROI rows."""
    statuses = [_as_text(value) for value in values if _as_text(value)]
    if not statuses:
        return "missing"
    return sorted(statuses, key=lambda status: STATUS_ORDER.get(status, 99))[0]


def _split_pipe(value: object) -> list[str]:
    """Split RCA pipe-separated recommendation fields into readable bullets."""
    text = _as_text(value)
    if not text:
        return []
    return [item.strip() for item in text.split(" | ") if item.strip()]


def _resolve_artifact_path(path_value: object) -> Path | None:
    """Resolve stored relative or absolute artifact paths to existing files."""
    text = _as_text(path_value)
    if not text:
        return None
    path = Path(text)
    if not path.is_absolute():
        path = ROOT / path
    return path if path.exists() else None


def _image_paths_from_quality_rows(quality_rows: pd.DataFrame) -> list[Path]:
    """Collect segmentation/QC overlay images saved by the quality-check step."""
    paths: list[Path] = []
    seen: set[Path] = set()
    for _, row in quality_rows.iterrows():
        candidates = [row.get("output_image_path"), row.get("image_path")]
        candidates.extend(_read_json(row.get("qc_data_json")).get(key) for key in ("output_image_path", "image_path"))
        for candidate in candidates:
            path = _resolve_artifact_path(candidate)
            if path is not None and path not in seen:
                seen.add(path)
                paths.append(path)
    return paths


