def main() -> None:
    """Streamlit entry point for the final dashboard."""
    _configure_page()
    st.sidebar.title("AI4Quality")
    st.sidebar.caption("Final clinical dashboard")

    if "final_dashboard_refresh" not in st.session_state:
        st.session_state.final_dashboard_refresh = 0
    if "final_dashboard_force_rebuild" not in st.session_state:
        st.session_state.final_dashboard_force_rebuild = False
    if st.sidebar.button("Refresh database", width="stretch"):
        st.cache_data.clear()
        st.session_state.final_dashboard_refresh += 1
        st.session_state.final_dashboard_force_rebuild = True

    try:
        db_mtime_ns = DB_PATH.stat().st_mtime_ns if DB_PATH.exists() else 0
        data = _load_database(st.session_state.final_dashboard_refresh, st.session_state.final_dashboard_force_rebuild, db_mtime_ns)
        st.session_state.final_dashboard_force_rebuild = False
    except Exception as exc:
        st.error(f"Unable to load the consolidated database: {exc}")
        st.info("Run QC/RCA first, then run: python _04_Recommendations/generate_recommendations.py")
        return

    series_summary = _series_summary(data)
    patient_summary = _patient_summary(series_summary, data)
    if patient_summary.empty:
        st.warning("No analyzed cases are available. Run preprocessing, quality check, and RCA first.")
        return

    filtered_patients, filtered_series = _filter_data(series_summary, patient_summary)
    _metric_row(filtered_patients, filtered_series)
    selected_ct_id = _patient_selector(filtered_patients)
    if selected_ct_id is None:
        return

    patient_row = filtered_patients[filtered_patients["ct_id"].astype(str).eq(selected_ct_id)].iloc[0]
    patient_series = filtered_series[filtered_series["ct_id"].astype(str).eq(selected_ct_id)].copy()

    _render_patient_header(patient_row)
    _render_warnings(patient_row)

    narrative_col, image_col = st.columns([0.92, 1.08], gap="large")
    with image_col:
        selected_series, quality_rows, rca_rows, image_paths = _selected_series_context(data, patient_series, selected_ct_id)
        _render_image_panel(selected_series, image_paths)
    with narrative_col:
        _render_recommendation(data, selected_ct_id)
        st.subheader("Analyzed series")
        _render_series_table(patient_series)
        if selected_series is not None:
            _render_selected_series_card(selected_series)
            _render_series_detail(quality_rows, rca_rows)

    _render_extra_data(data, selected_ct_id)


if __name__ == "__main__":
    main()