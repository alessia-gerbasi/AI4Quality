def _database_has_required_tables(path: Path) -> bool:
    """Check whether the SQLite file contains the tables this dashboard needs."""
    if not path.exists():
        return False
    try:
        with sqlite3.connect(path) as db:
            tables = {row[0] for row in db.execute("SELECT name FROM sqlite_master WHERE type='table'")}
            exam_columns = {row[1] for row in db.execute("PRAGMA table_info(exams)")} if "exams" in tables else set()
    except sqlite3.Error:
        return False
    required = {"series", "image_quality", "rca", "injector_data", "patient_warnings", "recommendations"}
    return required.issubset(tables) and "patient_name" not in exam_columns


@st.cache_data(show_spinner=False)
def _load_database(refresh_token: int, force_rebuild: bool, db_mtime_ns: int) -> dict[str, pd.DataFrame]:
    """Load the consolidated database, rebuilding source tables when necessary.

    The refresh_token argument is intentionally unused except as a Streamlit cache
    key. Incrementing it lets the sidebar Refresh button force a fresh read.
    """
    del refresh_token, db_mtime_ns

    if force_rebuild or not _database_has_required_tables(DB_PATH):
        build_database(DB_PATH)

    with sqlite3.connect(DB_PATH) as db:
        return {
            table: pd.read_sql_query(f"SELECT * FROM {table}", db)
            for table in ("exams", "series", "image_quality", "rca", "injector_data", "patient_warnings", "recommendations")
        }


def _series_summary(data: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Build one row per analyzed series with QC, RCA, and metadata labels."""
    series = data["series"].copy()
    quality = data["image_quality"].copy()
    rca = data["rca"].copy()
    phase_predictions = _phase_prediction_map(data)

    if series.empty and quality.empty:
        return pd.DataFrame()

    # QC is ROI-level; this aggregation gives clinicians the worst status and the
    # number of affected ROIs while keeping the detailed ROI rows expandable later.
    qc_summary = pd.DataFrame()
    if not quality.empty:
        qc_summary = quality.groupby(["ct_id", "series_folder"], dropna=False).agg(
            worst_status=("status", _worst_status),
            n_roi=("roi_name", "count"),
            n_critical=("status", lambda values: sum(_as_text(value).startswith("critical") for value in values)),
            n_missing=("status", lambda values: sum(_as_text(value) == "missing" for value in values)),
            affected_rois=("roi_name", _join_unique),
            metrics=("metric_name", _join_unique),
        ).reset_index()

    # RCA may have several schemas per series. Compact labels and schemas so the
    # table remains scan-friendly, then show the full rows in the detail panel.
    rca_summary = pd.DataFrame()
    if not rca.empty:
        rca_summary = rca.groupby(["ct_id", "series_folder"], dropna=False).agg(
            rca_labels=("rca_label", _join_unique),
            rca_schemas=("rca_schema", _join_unique),
            n_rca=("rca_schema", "count"),
        ).reset_index()

    keys = qc_summary[["ct_id", "series_folder"]].drop_duplicates() if not qc_summary.empty else pd.DataFrame()
    if keys.empty and not rca_summary.empty:
        keys = rca_summary[["ct_id", "series_folder"]].drop_duplicates()

    output = keys.merge(series, on=["ct_id", "series_folder"], how="left")
    if not qc_summary.empty:
        output = output.merge(qc_summary, on=["ct_id", "series_folder"], how="left")
    if not rca_summary.empty:
        output = output.merge(rca_summary, on=["ct_id", "series_folder"], how="left")

    for column in ("phase_name", "procedure_code", "scanner", "worst_status", "affected_rois", "metrics", "rca_labels", "rca_schemas"):
        if column not in output.columns:
            output[column] = ""
        output[column] = output[column].fillna("").astype(str)
    output["procedure_code"] = output["procedure_code"].replace("", UNSPECIFIED_PROCEDURE)
    output["phase_name"] = output["phase_name"].replace("", UNSPECIFIED_PHASE)
    output["scanner"] = output["scanner"].replace("", UNSPECIFIED_SCANNER)
    output["worst_status"] = output["worst_status"].replace("", NO_QC_STATUS)
    output["rca_labels"] = output["rca_labels"].replace({"": NO_RCA_LABEL, "-": NO_RCA_LABEL})
    output["n_roi"] = pd.to_numeric(output.get("n_roi", 0), errors="coerce").fillna(0).astype(int)
    output["n_critical"] = pd.to_numeric(output.get("n_critical", 0), errors="coerce").fillna(0).astype(int)
    output["n_missing"] = pd.to_numeric(output.get("n_missing", 0), errors="coerce").fillna(0).astype(int)
    output["n_rca"] = pd.to_numeric(output.get("n_rca", 0), errors="coerce").fillna(0).astype(int)
    output["actual_phase"] = output.apply(_effective_phase, axis=1)
    output["predicted_phase"] = [
        _as_text(phase_predictions.get((str(row.ct_id), str(row.series_folder)), {}).get("phase"))
        for row in output.itertuples(index=False)
    ]
    output["predicted_phase_probability"] = [
        phase_predictions.get((str(row.ct_id), str(row.series_folder)), {}).get("probability")
        for row in output.itertuples(index=False)
    ]
    output["phase_prediction_matches"] = [
        _phase_prediction_matches(_normalize_phase_name(actual), _normalize_phase_name(predicted))
        if predicted else pd.NA
        for actual, predicted in zip(output["actual_phase"], output["predicted_phase"], strict=False)
    ]
    output["phase_name"] = output["actual_phase"].replace("", UNSPECIFIED_PHASE)
    return output


def _patient_summary(series_summary: pd.DataFrame, data: dict[str, pd.DataFrame]) -> pd.DataFrame:
    """Build one row per patient for filtering, navigation, and top KPIs."""
    if series_summary.empty:
        return pd.DataFrame()

    patients = series_summary.groupby("ct_id", dropna=False).agg(
        n_series=("series_folder", "nunique"),
        n_critical_series=("worst_status", lambda values: sum(_as_text(value).startswith("critical") for value in values)),
        n_rca_series=("n_rca", lambda values: sum(int(value) > 0 for value in values)),
        n_missing_segmentations=("n_missing", lambda values: sum(int(value) > 0 for value in values)),
        procedures=("procedure_code", _join_unique),
        phases=("phase_name", _join_unique),
        scanners=("scanner", _join_unique),
    ).reset_index()

    warnings = data["patient_warnings"].copy()
    if warnings.empty:
        patients["warning_priority"] = "none"
        patients["warning"] = ""
        patients["segmentation_warning"] = ""
    else:
        patients = patients.merge(warnings, on="ct_id", how="left")
        patients["warning_priority"] = patients["warning_priority"].fillna("none").astype(str)
        for column in ("warning", "warning_evidence", "segmentation_warning", "segmentation_warning_evidence"):
            if column not in patients.columns:
                patients[column] = ""
            patients[column] = patients[column].fillna("").astype(str)

    recommendations = data["recommendations"].copy()
    if recommendations.empty:
        patients["has_recommendation"] = False
        patients["recommendation_created_at"] = ""
    else:
        current = recommendations[recommendations["scope"].fillna("").astype(str).eq("exam")].copy()
        current = current.sort_values("created_at").drop_duplicates("ct_id", keep="last")
        patients = patients.merge(current[["ct_id", "created_at"]], on="ct_id", how="left")
        patients["has_recommendation"] = patients["created_at"].notna()
        patients["recommendation_created_at"] = patients["created_at"].fillna("").astype(str)
        patients = patients.drop(columns=["created_at"], errors="ignore")

    patients["ct_folder"] = "CT_QUALITY_" + patients["ct_id"].astype(str)
    return patients.sort_values("ct_id", key=lambda column: column.map(_sort_key))


def _filter_data(series_summary: pd.DataFrame, patient_summary: pd.DataFrame) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Render sidebar controls and return the filtered patient and series rows."""
    with st.sidebar:
        st.header("Filters")
        search = st.text_input("Search CT, procedure, or scanner", value="")
        procedure_options = sorted({_as_text(value) for value in series_summary["procedure_code"] if _as_text(value)})
        phase_options = sorted({_as_text(value) for value in series_summary["phase_name"] if _as_text(value)})
        scanner_options = sorted({_as_text(value) for value in series_summary["scanner"] if _as_text(value)})
        status_options = sorted({_as_text(value) for value in series_summary["worst_status"] if _as_text(value)}, key=lambda value: STATUS_ORDER.get(value, 99))
        rca_options = sorted({_as_text(label) for labels in series_summary["rca_labels"] for label in labels.split(", ") if _as_text(label)})
        warning_options = list(WARNING_LABELS.keys())

        procedures = st.multiselect("Procedure", procedure_options, default=procedure_options)
        phases = st.multiselect("Phase", phase_options, default=phase_options)
        scanners = st.multiselect("Scanner", scanner_options, default=scanner_options)
        statuses = st.multiselect("QC status", status_options, default=status_options, format_func=lambda value: STATUS_LABELS.get(value, value))
        rca_labels = st.multiselect("Root cause", rca_options, default=rca_options)
        warning_priorities = st.multiselect("Warning priority", warning_options, default=warning_options, format_func=lambda value: WARNING_LABELS.get(value, value))
        recommendation_state = st.radio("LLM report", ["All", "Generated", "Missing"], horizontal=False)

    filtered_series = series_summary.copy()
    if procedures:
        filtered_series = filtered_series[filtered_series["procedure_code"].isin(procedures)]
    if phases:
        filtered_series = filtered_series[filtered_series["phase_name"].isin(phases)]
    if scanners:
        filtered_series = filtered_series[filtered_series["scanner"].isin(scanners)]
    if statuses:
        filtered_series = filtered_series[filtered_series["worst_status"].isin(statuses)]
    if rca_labels:
        filtered_series = filtered_series[filtered_series["rca_labels"].apply(lambda text: any(label in str(text).split(", ") for label in rca_labels))]

    allowed_patient_ids = set(filtered_series["ct_id"].astype(str))
    filtered_patients = patient_summary[patient_summary["ct_id"].astype(str).isin(allowed_patient_ids)].copy()
    filtered_patients = filtered_patients[filtered_patients["warning_priority"].fillna("none").isin(warning_priorities)]
    if recommendation_state == "Generated":
        filtered_patients = filtered_patients[filtered_patients["has_recommendation"]]
    elif recommendation_state == "Missing":
        filtered_patients = filtered_patients[~filtered_patients["has_recommendation"]]

    if search.strip():
        needle = search.strip().lower()
        haystack = filtered_patients[["ct_id", "ct_folder", "procedures", "scanners", "phases"]].fillna("").agg(" ".join, axis=1).str.lower()
        filtered_patients = filtered_patients[haystack.str.contains(needle, regex=False)]

    allowed_patient_ids = set(filtered_patients["ct_id"].astype(str))
    filtered_series = filtered_series[filtered_series["ct_id"].astype(str).isin(allowed_patient_ids)]
    return filtered_patients, filtered_series


